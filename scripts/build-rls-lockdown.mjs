#!/usr/bin/env node
/**
 * Put row level security back on, and on the two tables that never had it.
 *
 *   node scripts/build-rls-lockdown.mjs          # validate
 *   node scripts/build-rls-lockdown.mjs --emit   # write it
 *
 * WHAT WAS FOUND, AND WHAT THE FIRST PROBE ACTUALLY PROVED (nothing).
 *
 * The alarm that prompted this migration was a PATCH sent with the anon key,
 * with a WHERE matching no rows, against every content table. All of them
 * answered 204, which was read as "anon can write, RLS is off".
 *
 * That probe cannot show any such thing. PostgREST answers 204 to an UPDATE
 * that matched zero rows whether RLS is refusing the write or there was simply
 * nothing to update. Both states look identical. The correct probe is INSERT,
 * which does not depend on matching an existing row: RLS either permits it or
 * refuses it. Run afterwards, INSERT was refused on all eight tables.
 *
 * So it is NOT established that RLS was off beforehand, and this header no
 * longer claims it was. What is established is the after-state -- inserts
 * refused, reads working -- and the assertions at the foot of this migration,
 * which check pg_class and pg_policies directly rather than inferring from an
 * HTTP status.
 *
 * WHAT IS INDEPENDENTLY TRUE, and is the reason to keep this migration:
 *
 *   poojas and pooja_steps -- the two tables the app actually reads -- are
 *   protected nowhere in supabase/migrations. Their RLS came from a dashboard
 *   click and survives in the repo only as a stub at the top of the test
 *   harness. A database rebuilt from the migrations alone would come up with the
 *   two most important tables wide open, and nothing in version control would
 *   say otherwise. That gap is real, predates today, and is now closed and
 *   asserted by test:db.
 *
 * THE RISK BEING GUARDED AGAINST is integrity, not disclosure. Nothing in this
 * schema is private. The rows are liturgy that people recite, and there is no
 * undo but replaying migrations. The anon key is not in the browser bundle today
 * -- every Supabase call is made from a server component -- but NEXT_PUBLIC_
 * means Next.js inlines it the moment a client component imports it, and
 * Supabase treats that key as public regardless.
 *
 * WHAT THIS DOES. Enables RLS on every content table, including the two that
 * were missed, and creates exactly one policy per table: SELECT, using (true).
 * No insert, update or delete policy exists for anon, so those are refused.
 *
 * WHY THIS DOES NOT BREAK ANYTHING.
 *
 *   The app only reads. The only write in src/ is cache.delete() on an
 *   in-memory Map in the geocode route, not a database call.
 *
 *   Migrations are unaffected: they are run in the Supabase SQL editor as the
 *   table owner, and RLS does not apply to the owner. That is also why this
 *   uses `enable row level security` and NOT `force`, which WOULD apply to the
 *   owner and would make the next migration fail.
 *
 *   user_sessions keeps its own per-user policies from 0001 and is not touched.
 */
import { emitMigration } from './_migration.mjs';

/** Public reference content: everyone may read, nobody may write through the API. */
const READ_ONLY = [
  'poojas',
  'pooja_steps',
  'deities',
  'upachara_templates',
  'namavalis',
  'namavali_items',
  'archana_items',
  'samagri_items',
  'naivedyam_items',
  'media_assets',
  'pooja_date_overrides',
];

/** Left alone: it already has per-user policies and must stay writable by its owner. */
const UNTOUCHED = ['user_sessions'];

let failed = false;
console.log('--- tables to be made read-only through the API ---');
for (const t of READ_ONLY) console.log('  ' + t);
console.log('\n--- left alone ---');
for (const t of UNTOUCHED) console.log('  ' + t + '  (has its own per-user policies from 0001)');

if (READ_ONLY.some((t) => UNTOUCHED.includes(t))) {
  failed = true;
  console.error('  FAIL a table is in both lists');
}
if (!READ_ONLY.includes('poojas') || !READ_ONLY.includes('pooja_steps')) {
  failed = true;
  console.error('  FAIL the two tables that were never protected must be in the list');
}
if (failed) { console.error('\nnot emitting'); process.exit(1); }

const lines = [];
const out = (s = '') => lines.push(s);

out('-- =============================================================================');
out('-- 0038_rls_read_only.sql');
out('--');
out('-- GENERATED by scripts/build-rls-lockdown.mjs. Do not hand-edit.');
out('--');
out('-- WHAT PROMPTED THIS, AND A CORRECTION. The alarm was a PATCH sent with the');
out('-- anon key, WHERE matching no rows, which answered 204 on every table and was');
out('-- read as "anon can write". That proves nothing: PostgREST answers 204 to an');
out('-- update matching zero rows whether RLS refused it or there was nothing to');
out('-- update. INSERT is the probe that discriminates, and afterwards it was');
out('-- refused everywhere. So it is NOT established that RLS was off beforehand.');
out('--');
out('-- The reason to keep this migration is independent of that:');
out('--');
out('--   poojas and pooja_steps -- the two tables the app reads -- are protected');
out('--   nowhere in supabase/migrations. Their RLS came from a dashboard click and');
out('--   survives in the repo only as a stub in the test harness. A database built');
out('--   from migrations alone would come up with them wide open and nothing in');
out('--   version control would say so.');
out('--');
out('-- The risk is integrity, not disclosure: nothing here is private, but the rows');
out('-- are liturgy people recite and there is no undo but replaying migrations.');
out('--');out('-- Every content table gets RLS and exactly one policy: select using (true).');
out('-- No insert, update or delete policy exists for anon, so those are refused.');
out('--');
out('-- `enable`, NOT `force`. Forced RLS applies to the table owner too, and');
out('-- migrations are run as the owner in the SQL editor -- forcing it would make');
out('-- the next migration fail. user_sessions keeps its own per-user policies.');
out('--');
out('-- Idempotent, and safe on a database missing any of these tables.');
out('-- =============================================================================');
out();
out('begin;');
out();
out('do $$');
out('declare t text;');
out('begin');
out('  foreach t in array array[');
out('    ' + READ_ONLY.map((x) => `'${x}'`).join(',\n    '));
out('  ] loop');
out('    -- to_regclass returns null rather than raising, so a database that does');
out('    -- not have one of these tables is skipped instead of failing.');
out("    if to_regclass('public.' || t) is null then");
out("      raise notice 'skipping %, which does not exist here', t;");
out('      continue;');
out('    end if;');
out();
out("    execute format('alter table public.%I enable row level security', t);");
out();
out('    if not exists (');
out('      select 1 from pg_policies');
out("       where schemaname = 'public' and tablename = t");
out("         and policyname = 'public read ' || t");
out('    ) then');
out('      execute format(');
out("        'create policy %I on public.%I for select using (true)',");
out("        'public read ' || t, t);");
out('    end if;');
out();
out('    -- Anything that lets anon write is removed. A permissive FOR ALL policy');
out('    -- reads as harmless next to a select policy and is not.');
out('    declare p record;');
out('    begin');
out('      for p in');
out('        select policyname, cmd from pg_policies');
out("         where schemaname = 'public' and tablename = t");
out("           and cmd <> 'SELECT'");
out('      loop');
out("        raise notice 'dropping % policy % on %', p.cmd, p.policyname, t;");
out("        execute format('drop policy %I on public.%I', p.policyname, t);");
out('      end loop;');
out('    end;');
out('  end loop;');
out('end $$;');
out();
out('-- --- assert ------------------------------------------------------------------');
out('do $$');
out('declare t text; n int;');
out('begin');
out('  foreach t in array array[');
out('    ' + READ_ONLY.map((x) => `'${x}'`).join(',\n    '));
out('  ] loop');
out("    if to_regclass('public.' || t) is null then continue; end if;");
out();
out('    select count(*) into n from pg_class c');
out('      join pg_namespace ns on ns.oid = c.relnamespace');
out("     where ns.nspname = 'public' and c.relname = t and c.relrowsecurity;");
out("    if n <> 1 then raise exception 'row level security is not enabled on %', t; end if;");
out();
out('    select count(*) into n from pg_policies');
out("     where schemaname = 'public' and tablename = t and cmd = 'SELECT';");
out("    if n < 1 then raise exception '% has no select policy, so nothing can read it', t; end if;");
out();
out('    select count(*) into n from pg_policies');
out("     where schemaname = 'public' and tablename = t and cmd <> 'SELECT';");
out("    if n > 0 then raise exception '% still has % non-select policies', t, n; end if;");
out('  end loop;');
out();
out('  -- user_sessions must KEEP its write policies; this migration must not have');
out('  -- stripped them.');
out("  if to_regclass('public.user_sessions') is not null then");
out('    select count(*) into n from pg_policies');
out("     where schemaname = 'public' and tablename = 'user_sessions' and cmd <> 'SELECT';");
out("    if n < 1 then raise exception 'user_sessions lost its own write policies'; end if;");
out('  end if;');
out('end $$;');
out();
out('commit;');

const sql = lines.join('\n') + '\n';
if (process.argv.includes('--emit')) {
  emitMigration('supabase/migrations/0038_rls_read_only.sql', sql);
  console.log('\nwrote supabase/migrations/0038_rls_read_only.sql');
} else {
  console.log('\n--- validated, not written (pass --emit) ---');
}
