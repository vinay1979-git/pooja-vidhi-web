#!/usr/bin/env node
/**
 * A section label for steps: "Shodashopachara · 3 of 9".
 *
 *   node scripts/build-step-sections.mjs --emit   # write 0061
 *
 * docs/plans/ux-seamless-flow.md §3.1. Splitting a bundled step so that each
 * screen holds one offering and its verse makes rites roughly twice as long in
 * steps, and a reader needs to know where they are within the run of
 * upacharas, not only within the whole rite. The label is that orientation.
 *
 * Schema only: two nullable text columns. Nothing is filled here; the rite
 * rebuilds that split their steps (0062 onwards) set them. The viewer selects
 * them with a fallback (src/lib/queries.ts), so code and migration can land in
 * either order, and a step without a section renders exactly as before.
 */
import { emitMigration } from './_migration.mjs';

const sql = `-- Section labels for steps. Generated by scripts/build-step-sections.mjs.

begin;

alter table public.pooja_steps add column if not exists section_en text;
alter table public.pooja_steps add column if not exists section_ta text;

comment on column public.pooja_steps.section_en is
  'The group a step belongs to, e.g. Shodashopachara. Shown above the title with the position inside the run of consecutive steps sharing it. Null for a step that stands alone.';
comment on column public.pooja_steps.section_ta is
  'section_en in Tamil.';

commit;
`;

if (!process.argv.includes('--emit')) {
  console.log('(no SQL written; pass --emit)');
  process.exit(0);
}
emitMigration('supabase/migrations/0061_step_sections.sql', sql);
