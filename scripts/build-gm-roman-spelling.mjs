#!/usr/bin/env node
/**
 * Spell the gm nasal gm in roman, not gum.
 *
 *   node scripts/build-gm-roman-spelling.mjs          # validate
 *   node scripts/build-gm-roman-spelling.mjs --emit   # write it
 *
 * 0045 taught the transliterator the sign and settled its reading on the
 * evidence then available: the Nitya Pooja volume romanises it gum,
 * gaNapatigum havaamahE. Transcribing the Sandhyavandanam produced better
 * evidence. That book spells it gm throughout -- idagm, chandaagmsyaapaha,
 * jyoteegmshyaapaha, yajoogmshyaapaha, ogm, four times on book page 20 alone --
 * so gum is the outlier and gm is what Giri's own Sandhyavandanam uses.
 *
 * ROMAN ONLY. The Devanagari is ꣳ either way and is untouched. So is the Tamil:
 * Tamil cannot write a bare gm without a vowel, so கும் remains the only
 * sensible rendering and 0045 already got it right. This migration exists
 * because one column of one rule changed, not because the reading did -- gum
 * and gm are the same sound, differing only in whether the inherent vowel is
 * written.
 *
 * REGENERATED FROM THE DEVANAGARI, like 0045, and keyed on
 * (pooja_id, step_title_en) for the same reason: pooja_steps.id is generated
 * per insert, so an update keyed on id matches nothing in a database rebuilt
 * from migrations and the migration passes by doing nothing at all. 0045's
 * first draft did precisely that.
 */
import { readFileSync } from 'node:fs';
import Sanscript from '@indic-transliteration/sanscript';
import { transliterate } from './_tamil.mjs';
import { emitMigration } from './_migration.mjs';

const S = Sanscript.default ?? Sanscript;
const GM = 'ꣳ';

const env = Object.fromEntries(
  readFileSync('.env.local', 'utf8')
    .split(/\r?\n/)
    .filter((l) => l.trim() && !l.trim().startsWith('#'))
    .map((l) => {
      const i = l.indexOf('=');
      return [l.slice(0, i).trim(), l.slice(i + 1).trim()];
    }),
);
const headers = {
  apikey: env.NEXT_PUBLIC_SUPABASE_ANON_KEY,
  Authorization: `Bearer ${env.NEXT_PUBLIC_SUPABASE_ANON_KEY}`,
};

const steps = await (
  await fetch(
    `${env.NEXT_PUBLIC_SUPABASE_URL}/rest/v1/pooja_steps` +
      '?select=pooja_id,step_number,step_title_en,mantra_sanskrit,mantra_tamil,mantra_translit&limit=5000',
    { headers },
  )
).json();

let failed = false;
const fail = (m) => { failed = true; console.error('  FAIL ' + m); };

const affected = steps.filter((s) => (s.mantra_sanskrit || '').includes(GM));

console.log('--- roman respelled gum -> gm ---');
const edits = [];
for (const s of affected) {
  const translit = transliterate(S, s.mantra_sanskrit, 'iast');
  const tamil = transliterate(S, s.mantra_sanskrit, 'tamil');
  const at = `${s.pooja_id} #${s.step_number} ${s.step_title_en}`;
  console.log(`  ${at}`);

  if (/gum/.test(translit)) fail(`${at}: regenerated roman still says gum`);
  if (!/gm/.test(translit)) fail(`${at}: regenerated roman does not say gm`);
  if (translit === s.mantra_translit) fail(`${at}: roman is unchanged, so nothing was respelled`);
  // The Tamil must be BYTE-IDENTICAL to what is already stored. If this rule
  // change moved the Tamil too, something was wired to the wrong branch.
  if (tamil !== s.mantra_tamil) fail(`${at}: Tamil changed, and this migration must not touch it`);

  edits.push({ pooja: s.pooja_id, title: s.step_title_en, at, translit });
}
if (edits.length !== 4) fail(`expected four rows, found ${edits.length}`);
if (failed) { console.error('\nnot emitting'); process.exit(1); }

const q = (s) => `'${String(s).replace(/'/g, "''")}'`;
const lines = [];
const out = (s = '') => lines.push(s);

out('-- =============================================================================');
out('-- 0046_gm_roman_spelling.sql');
out('--');
out('-- GENERATED by scripts/build-gm-roman-spelling.mjs. Do not hand-edit.');
out('--');
out('-- 0045 settled the gm nasal on the evidence then available: the Nitya Pooja');
out('-- volume romanises it gum. Transcribing the Sandhyavandanam produced better');
out('-- evidence -- that book spells it gm throughout, four times on book page 20');
out('-- alone (idagm, chandaagmsyaapaha, jyoteegmshyaapaha, ogm), so gum is the');
out('-- outlier and gm is what Giri\'s own Sandhyavandanam uses.');
out('--');
out('-- ROMAN ONLY. The Devanagari is ꣳ either way. So is the Tamil: it cannot write');
out('-- a bare gm without a vowel, so கும் stands and 0045 already got it right.');
out('-- The reading has not changed -- gum and gm are the same sound, differing only');
out('-- in whether the inherent vowel is written.');
out('-- =============================================================================');
out();
out('begin;');
out();
for (const e of edits) {
  out(`-- ${e.at}`);
  out('update public.pooja_steps set');
  out(`       mantra_translit = ${q(e.translit)},`);
  out('       updated_at      = now()');
  out(` where pooja_id = ${q(e.pooja)} and step_title_en = ${q(e.title)};`);
  out();
}
out('-- --- assert ------------------------------------------------------------------');
out('do $$');
out('declare n int;');
out('begin');
out('  select count(*) into n from public.pooja_steps');
out("   where coalesce(mantra_translit, '') like '%gum%';");
out("  if n <> 0 then raise exception '% roman mantra(s) still say gum', n; end if;");
out();
out('  -- Scoped by name. An unscoped count of roman containing gm would also');
out('  -- match any ordinary g followed by m, which is not what is being asserted.');
out('  select count(*) into n from public.pooja_steps');
out(`   where pooja_id = ${q(edits[0].pooja)}`);
out(`     and step_title_en in (${edits.map((e) => q(e.title)).join(', ')})`);
out("     and mantra_translit like '%gm%';");
out(`  if n <> ${edits.length} then raise exception 'only % of the ${edits.length} step(s) say gm', n; end if;`);
out();
out('  -- The Tamil was NOT touched, and the Devanagari still carries the sign.');
out('  select count(*) into n from public.pooja_steps');
out("   where mantra_tamil like '%கும்%' and pooja_id = " + q(edits[0].pooja) + ';');
out(`  if n < ${edits.length} then raise exception 'the Tamil lost கும்: only % row(s) keep it', n; end if;`);
out();
out('  select count(*) into n from public.pooja_steps');
out(`   where coalesce(mantra_sanskrit, '') like '%${GM}%';`);
out(`  if n <> ${edits.length} then raise exception 'expected ${edits.length} step(s) to keep the sign in Devanagari, found %', n; end if;`);
out('end $$;');
out();
out('commit;');

const sql = lines.join('\n') + '\n';
if (process.argv.includes('--emit')) {
  emitMigration('supabase/migrations/0046_gm_roman_spelling.sql', sql);
  console.log('\nwrote supabase/migrations/0046_gm_roman_spelling.sql');
} else {
  console.log('\n--- validated, not written (pass --emit) ---');
}
