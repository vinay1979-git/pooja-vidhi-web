#!/usr/bin/env node
/**
 * Varalakshmi's Prana Pratishtha, made to talk about Varalakshmi.
 *
 *   node scripts/build-prana-note-repair.mjs          # validate
 *   node scripts/build-prana-note-repair.mjs --emit   # write 0059
 *
 * Two pieces of prose on this one step describe something other than what
 * the reader is looking at:
 *
 *   philosophy_en compared the step to "Ganesha Chaturthi" and said the
 *   feminine forms are how "the published Lalitha vidhanam" writes them --
 *   another festival and an edition the reader has never seen, in a pooja that
 *   is neither. The point it was making stands and is kept: the verse asks for
 *   breath and sight back before it asks the goddess anything, and the
 *   feminine bhava lines are why the kalasham later needs a step of its own to
 *   be released.
 *
 *   instruction_en and instruction_ta said the verse is used in its feminine
 *   form "asyai rather than asya". The mantra has no asyai; that was the
 *   asyai pranah pratishthantu verse, which 0021 replaced. The feminine here is
 *   avahita, sthapita, varada.
 *
 * Each UPDATE writes only where the field still differs, and the migration
 * refuses to commit unless all three fields hold the new text and the phrase
 * the philosophy quotes is in the step's own roman mantra.
 */
import { emitMigration } from './_migration.mjs';

const MIGRATION = 'supabase/migrations/0059_varalakshmi_prana_note.sql';
const STEP = `pooja_id = 'varalakshmi_vratham' and step_title_en = 'Prana Pratishtha'`;

const NEW = {
  philosophy_en:
    'Asunite punarasmasu chakshuh, "give us back our sight". The verse asks that breath, sight and gladness be returned to us before it asks anything of the goddess. Only then do the lines turn to her, and they turn in the feminine: avahita bhava, sthapita bhava, varada bhava, be invoked, be established, be the giver of boons. From that moment the kalasham is treated as a presence, which is why it is released the next day with a step of its own rather than simply being put away.',
  instruction_en:
    'Touch the kalasham with the fingertips of the right hand and ask the life breath to settle into it. From here the kalasham is treated as present, not as an arrangement of vessels. The closing lines address the goddess in the feminine: avahita, sthapita, varada.',
  instruction_ta:
    'வலது கை விரல் நுனிகளால் கலசத்தைத் தொட்டு, உயிர்ப்பு அதில் நிலைபெறும்படி வேண்டவும். இதற்குப் பின் கலசம் பாத்திரங்களின் அமைப்பு அல்ல; எழுந்தருளியிருப்பவளாகவே கருதப்படுகிறது. இறுதி வரிகள் தேவியை ஸ்த்ரீலிங்கத்தில் அழைக்கின்றன — ஆவாஹிதா, ஸ்தாபிதா, வரதா.',
};
// Phrases the new prose quotes, as they appear in mantra_translit.
const QUOTED = ['asunīte punarasmāsu cakṣuḥ', 'āvāhitā bhava', 'sthāpitā bhava', 'varadā bhava'];

let failed = false;
const fail = (m) => { failed = true; console.error('FAIL ' + m); };
for (const [k, v] of Object.entries(NEW)) {
  if (/Ganesha|Chaturthi|Lalitha|vidhanam|asyai|the book|edition/i.test(v)) fail(`${k} still names another rite, an edition or asyai`);
  if (k.endsWith('_ta') && !/[஀-௿]/.test(v)) fail(`${k} is not Tamil`);
  console.log(`  ${k}: ${v.slice(0, 90)}...`);
}
if (failed) process.exit(1);
if (!process.argv.includes('--emit')) { console.log('\n(no SQL written; pass --emit)'); process.exit(0); }

const q = (s) => `'${s.replace(/'/g, "''")}'`;
const sql = `-- Varalakshmi's Prana Pratishtha: the note and the instruction describe this
-- step, not Ganesha Chaturthi, an edition, or a verse it no longer carries.
-- Generated by scripts/build-prana-note-repair.mjs; see its header.

begin;

${Object.entries(NEW).map(([k, v]) => `update public.pooja_steps set ${k} = ${q(v)}, updated_at = now()
 where ${STEP} and ${k} is distinct from ${q(v)};`).join('\n\n')}

do $$
declare n int;
begin
  select count(*) into n from public.pooja_steps
   where ${STEP}
     and ${Object.entries(NEW).map(([k, v]) => `${k} = ${q(v)}`).join('\n     and ')};
  if n <> 1 then raise exception 'Prana Pratishtha: a field was not written'; end if;
  select count(*) into n from public.pooja_steps
   where ${STEP}
     and ${QUOTED.map((p) => `position(${q(p)} in mantra_translit) > 0`).join('\n     and ')};
  if n <> 1 then raise exception 'Prana Pratishtha: the note quotes a phrase the mantra does not have'; end if;
end $$;

commit;
`;
emitMigration(MIGRATION, sql);
