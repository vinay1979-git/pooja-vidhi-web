#!/usr/bin/env node
/**
 * The Tamil instructions 0032 forgot to give its two new steps.
 *
 *   node scripts/build-new-step-tamil.mjs          # validate
 *   node scripts/build-new-step-tamil.mjs --emit   # write it
 *
 * WHAT HAPPENED. 0032 inserted Dora Sthapanam and Avahanam with an English
 * instruction and no Tamil one. Every other step in both poojas has both, so on
 * a Tamil setting these two would have shown the English fallback -- the exact
 * thing the whole single-language UI pass was about.
 *
 * `npm run proofread` caught it the moment 0032 landed, which is the gate doing
 * its job: instruction_ta was the ONLY field the new steps lacked that their
 * neighbours have. (philosophy_ta is null on every step in the project, so it
 * is a standing gap rather than something 0032 introduced.)
 *
 * The lesson for the next insert: when adding a step, diff its column set
 * against an existing step of the same pooja rather than against the schema.
 * The schema says these columns are nullable; the data says they are not
 * optional.
 */
import { emitMigration } from './_migration.mjs';

const STEPS = [
  {
    en: 'Dora Sthapanam',
    ta:
      'தேவியை ஆவாஹனம் செய்வதற்கு முன், ஒன்பது முடிச்சுகள் கொண்ட நோன்பு சரடை ' +
      'சமர்ப்பணப் பொருட்களுடன் வைத்து, இந்த மந்திரத்தால் அதை ஆவாஹனம் செய்யவும். ' +
      'பூஜை முழுவதும் சரடு அங்கேயே இருக்கும்; இறுதியில் ஒவ்வொரு முடிச்சாகப் ' +
      'பூஜிக்கப்படும்.',
  },
  {
    en: 'Avahanam',
    ta:
      'மலர்களும் அக்ஷதையும் சமர்ப்பித்து, கலசத்தில் தேவியை ஆவாஹனம் செய்யவும்.',
  },
];

const TAMIL = /^[஀-௿ -ÿ\s.,;:!?'"()—–-]+$/;

let failed = false;
console.log('--- the replacements are Tamil, and not empty ---');
for (const s of STEPS) {
  if (!s.ta.trim()) { failed = true; console.error(`  FAIL ${s.en}: empty`); continue; }
  if (!TAMIL.test(s.ta)) { failed = true; console.error(`  FAIL ${s.en}: contains non-Tamil characters`); continue; }
  if (/[ऀ-ॿ]/.test(s.ta)) { failed = true; console.error(`  FAIL ${s.en}: Devanagari leaked in`); continue; }
  console.log(`  ${s.en.padEnd(18)} ${s.ta.length} chars`);
}
if (failed) { console.error('\nnot emitting'); process.exit(1); }

const q = (s) => `'${String(s).replace(/'/g, "''")}'`;
const lines = [];
const out = (s = '') => lines.push(s);

out('-- =============================================================================');
out('-- 0033_new_step_tamil_instructions.sql');
out('--');
out('-- GENERATED by scripts/build-new-step-tamil.mjs. Do not hand-edit.');
out('--');
out('-- 0032 inserted Dora Sthapanam and Avahanam with an English instruction and no');
out('-- Tamil one. On a Tamil setting those two steps would have fallen back to');
out('-- English, which is the one thing the single-language UI pass existed to stop.');
out('-- proofread caught it as soon as 0032 landed.');
out('--');
out('-- Idempotent: only fills an instruction_ta that is still missing.');
out('-- =============================================================================');
out();
out('begin;');
out();
for (const s of STEPS) {
  out(`update public.pooja_steps set instruction_ta = ${q(s.ta)}, updated_at = now()`);
  out(` where pooja_id = 'varalakshmi_vratham' and step_title_en = ${q(s.en)}`);
  out(`   and coalesce(trim(instruction_ta), '') = '';`);
  out();
}
out('-- --- assert ------------------------------------------------------------------');
out('do $$');
out('declare n int;');
out('begin');
out('  -- No step in either pooja may have an English instruction and no Tamil one.');
out('  select count(*) into n from public.pooja_steps');
out("   where coalesce(trim(instruction_en), '') <> ''");
out("     and coalesce(trim(instruction_ta), '') = '';");
out("  if n > 0 then raise exception '% steps have an English instruction and no Tamil', n; end if;");
out();
out('  -- And the Tamil is Tamil, not Devanagari that leaked across.');
out('  select count(*) into n from public.pooja_steps');
out("   where instruction_ta ~ '[\\u0900-\\u097F]';");
out("  if n > 0 then raise exception '% instruction_ta carry Devanagari', n; end if;");
out('end $$;');
out();
out('commit;');

const sql = lines.join('\n') + '\n';
if (process.argv.includes('--emit')) {
  emitMigration('supabase/migrations/0033_new_step_tamil_instructions.sql', sql);
  console.log('\nwrote supabase/migrations/0033_new_step_tamil_instructions.sql');
} else {
  console.log('\n--- validated, not written (pass --emit) ---');
}
