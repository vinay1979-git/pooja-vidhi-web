#!/usr/bin/env node
/**
 * Let a rite say at what hour each of its modes applies.
 *
 *   node scripts/build-mode-hours.mjs          # validate
 *   node scripts/build-mode-hours.mjs --emit   # write it
 *
 * The sandhyavandanam picker opens on the morning sitting whatever the time. It
 * should open on the one you are actually in, and be changeable -- that was the
 * agreed design, on a plain clock rule with no location.
 *
 * WHY THIS IS A COLUMN AND NOT THREE STRINGS IN THE CLIENT. The obvious
 * implementation is a map from hour to 'pratah' | 'madhyahnika' | 'sayam' in
 * PoojaViewer. That is exactly what 0047 took out: those names are this rite's,
 * the next nitya karma will have its own, and a component that knows them is a
 * component that has to be edited every time a rite is added. The rite declares
 * its own hours and the picker reads them.
 *
 * THE RULE IS THE READER'S CLOCK, NOT THE SUN. Sunrise and solar noon move by
 * weeks across the year and would need the place, the date and an almanac. The
 * book's own instruction for the evening japa is conditional on the actual
 * sunset -- facing west before it, east after -- and that one is printed as a
 * sentence for the reader to judge, because no clock can answer it. What the
 * picker needs is much weaker: a sensible opening guess that a tap corrects.
 *
 * NULL MEANS DO NOT GUESS. Ganesha and Varalakshmi have days, not hours; there
 * is no time of day at which a Punar Pooja becomes the right answer. Their rows
 * stay null and the picker leaves them on whatever it opened with.
 */
import { emitMigration } from './_migration.mjs';

/**
 * [pooja, mode, from_hour]. The mode applies from this local hour until the
 * next one begins; the last wraps to midnight.
 */
const HOURS = [
  ['sandhyavandanam', 'pratah', 0],
  ['sandhyavandanam', 'madhyahnika', 11],
  ['sandhyavandanam', 'sayam', 16],
];

let failed = false;
const fail = (m) => { failed = true; console.error('  FAIL ' + m); };

console.log('--- when each sitting begins ---');
const byPooja = {};
for (const [p, m, h] of HOURS) (byPooja[p] ??= []).push([m, h]);
for (const [p, list] of Object.entries(byPooja)) {
  const sorted = [...list].sort((a, b) => a[1] - b[1]);
  for (let i = 0; i < sorted.length; i += 1) {
    const [m, h] = sorted[i];
    const until = i + 1 < sorted.length ? sorted[i + 1][1] : 24;
    console.log(`  ${p.padEnd(18)} ${m.padEnd(13)} ${String(h).padStart(2)}:00 to ${String(until).padStart(2)}:00`);
  }
  // The first must start at midnight or there is an hour with no answer.
  if (sorted[0][1] !== 0) fail(`${p}: the earliest mode starts at ${sorted[0][1]}:00, leaving midnight uncovered`);
  const hrs = sorted.map(([, h]) => h);
  if (new Set(hrs).size !== hrs.length) fail(`${p}: two modes claim the same hour`);
  for (const [m, h] of list) {
    if (!Number.isInteger(h) || h < 0 || h > 23) fail(`${p}/${m}: ${h} is not an hour`);
  }
}
if (failed) { console.error('\nnot emitting'); process.exit(1); }

const q = (s) => `'${String(s).replace(/'/g, "''")}'`;
const lines = [];
const out = (s = '') => lines.push(s);

out('-- =============================================================================');
out('-- 0051_mode_hours.sql');
out('--');
out('-- GENERATED by scripts/build-mode-hours.mjs. Do not hand-edit.');
out('--');
out('-- A rite may say at what hour each of its modes applies, so the picker can open');
out('-- on the sitting you are actually in rather than always on the morning.');
out('--');
out('-- A COLUMN, NOT THREE STRINGS IN THE CLIENT. The obvious implementation is a');
out('-- map from hour to pratah/madhyahnika/sayam in PoojaViewer -- which is exactly');
out('-- what 0047 took out. Those names belong to this rite, the next nitya karma');
out('-- will have its own, and a component that knows them must be edited every time');
out('-- a rite is added.');
out('--');
out('-- THE READER\'S CLOCK, NOT THE SUN. Sunrise and solar noon move by weeks across');
out('-- the year and would need the place, the date and an almanac -- and the rite');
out('-- deliberately asks for none of those. The book\'s own sunset-dependent');
out('-- instruction, facing west before sunset and east after, is printed as a');
out('-- sentence for the reader to judge, because no clock can answer it. A picker');
out('-- needs only a sensible opening guess that one tap corrects.');
out('--');
out('-- NULL MEANS DO NOT GUESS. Ganesha and Varalakshmi have days, not hours: there');
out('-- is no time at which a Punar Pooja becomes the right answer. Their rows stay');
out('-- null and the picker leaves them alone.');
out('-- =============================================================================');
out();
out('begin;');
out();
out('alter table public.pooja_modes');
out('  add column if not exists from_hour integer;');
out();
out('do $$ begin');
out('  alter table public.pooja_modes');
out('    add constraint pooja_modes_from_hour_ck check (from_hour between 0 and 23);');
out('exception when duplicate_object or duplicate_table then null; end $$;');
out();
out('comment on column public.pooja_modes.from_hour is');
out(`  ${q('Local hour at which this mode becomes the current one, until the next begins. Null means the mode is not chosen by the clock -- a multi-day observance has days, not hours. A pooja that sets it on any mode must cover hour 0, or some hour has no answer.')};`);
out();
for (const [p, m, h] of HOURS) {
  out(`update public.pooja_modes set from_hour = ${h}, updated_at = now()`);
  out(` where pooja_id = ${q(p)} and mode = ${q(m)};`);
}
out();
out('-- --- assert ------------------------------------------------------------------');
out('do $$');
out('declare n int; r record;');
out('begin');
for (const [p, list] of Object.entries(byPooja)) {
  out(`  select count(*) into n from public.pooja_modes where pooja_id = ${q(p)} and from_hour is not null;`);
  out(`  if n <> ${list.length} then raise exception '${p} has % clock-tagged modes, expected ${list.length}', n; end if;`);
}
out();
out('  -- Whatever the hour, exactly one mode answers for it. Checked by walking all');
out('  -- twenty-four rather than trusting the three boundaries: an off-by-one at a');
out('  -- boundary is precisely the fault that would leave an hour unanswered, and it');
out('  -- would not show up in a count.');
out('  for r in select distinct pooja_id from public.pooja_modes where from_hour is not null loop');
out('    for n in 0..23 loop');
out('      if not exists (');
out('        select 1 from public.pooja_modes m');
out('         where m.pooja_id = r.pooja_id and m.from_hour is not null and m.from_hour <= n');
out('      ) then');
out("        raise exception 'no mode of % answers for hour %', r.pooja_id, n;");
out('      end if;');
out('    end loop;');
out('  end loop;');
out();
out('  -- A pooja with days must not have hours. Ganesha at 11:00 is not a Punar Pooja.');
out('  select count(*) into n from public.pooja_modes m');
out('    join public.poojas p on p.id = m.pooja_id');
// `is distinct from` rather than `<>`: a pooja whose ritual_class is null would
// make `<>` evaluate to null, the row would not be counted, and the gate would
// pass on exactly the case it exists to catch.
out("   where m.from_hour is not null and p.ritual_class is distinct from 'nitya';");
out("  if n > 0 then raise exception '% non-nitya mode(s) carry an hour', n; end if;");
out();
out('  -- Every clock-tagged mode still has steps, or the picker would open on an');
out('  -- empty list at that hour. 0047 checks this for modes generally; the clock');
out('  -- makes it sharper, because here the app chooses the mode rather than the');
out('  -- reader.');
out('  select count(*) into n from public.pooja_modes m');
out('   where m.from_hour is not null');
out('     and not exists (');
out('       select 1 from public.pooja_steps s');
out('        where s.pooja_id = m.pooja_id and m.mode = any(s.modes)');
out('     );');
out("  if n > 0 then raise exception '% clock-tagged mode(s) have no steps', n; end if;");
out('end $$;');
out();
out('commit;');

const sql = lines.join('\n') + '\n';
if (process.argv.includes('--emit')) {
  emitMigration('supabase/migrations/0051_mode_hours.sql', sql);
  console.log('\nwrote supabase/migrations/0051_mode_hours.sql');
} else {
  console.log('\n--- validated, not written (pass --emit) ---');
}
