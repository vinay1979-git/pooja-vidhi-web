#!/usr/bin/env node
/**
 * Fill the Devanagari that was missing, then derive Tamil and IAST from it.
 *
 * Anga Vandanam only ever had a loose roman transliteration, so switching the
 * mantra script did nothing on that step. The roman text cannot be converted
 * back reliably: "Keshavaya" could be केशवाय or खेशवाय, and "Namaha" is not
 * strict IAST for नमः. So the Devanagari is written out properly here, and the
 * other two scripts are generated from it, same as every other step.
 *
 * These are the twelve Keshavadi names of Vishnu touched to the body during
 * anga vandanam, in the standard order.
 *
 *   node scripts/fill-missing-devanagari.mjs --emit > supabase/migrations/0008_anga_vandanam_scripts.sql
 */

import Sanscript from '@indic-transliteration/sanscript';
import { tidyTamil, fixSuperscripts, transliterate as trShared, PROTECTED } from './_tamil.mjs';


// Tidy two artefacts of the plain Tamil scheme.
//  - visarga comes out as aytham; Tamil Sanskrit print uses a raised colon,
//    which is also what the archana rows already used.
//  - vocalic r and rr are marked with an ASCII apostrophe (kRShNa -> kru'Shna).
//    Tamil devotional print writes these plain, and a stray quote in the middle
//    of a mantra just looks like a typo.
const TAMIL_SCHEME = 'tamil';

function transliterate(text, to) {
  return String(text)
    .split(PROTECTED)
    .map((part) => {
      if (part === '' || PROTECTED.test(part)) return part;
      const done = Sanscript.t(part, 'devanagari', to);
      return to.startsWith('tamil') ? tidyTamil(fixSuperscripts(done)) : done;
    })
    .join('');
}

const ROWS = [
  {
    step: 'Anga Vandanam',
    deva:
      'ॐ केशवाय नमः । ॐ नारायणाय नमः । ॐ माधवाय नमः । ॐ गोविन्दाय नमः । ' +
      'ॐ विष्णवे नमः । ॐ मधुसूदनाय नमः । ॐ त्रिविक्रमाय नमः । ॐ वामनाय नमः । ' +
      'ॐ श्रीधराय नमः । ॐ हृषीकेशाय नमः । ॐ पद्मनाभाय नमः । ॐ दामोदराय नमः ॥',
  },
];

const q = (s) => `'${String(s).replace(/'/g, "''")}'`;
const emit = process.argv.includes('--emit');
const out = emit ? console.log : () => {};

for (const r of ROWS) {
  console.error(`${r.step}`);
  console.error(`  deva   ${r.deva.slice(0, 70)}...`);
  console.error(`  tamil  ${transliterate(r.deva, TAMIL_SCHEME).slice(0, 70)}...`);
  console.error(`  iast   ${transliterate(r.deva, 'iast').slice(0, 70)}...`);
}

out('-- =============================================================================');
out('-- 0008_anga_vandanam_scripts.sql');
out('--');
out('-- GENERATED by scripts/fill-missing-devanagari.mjs.');
out('--');
out('-- Anga Vandanam had only a loose roman transliteration, so the mantra script');
out('-- toggle did nothing on that step. The roman form cannot be converted back');
out('-- reliably, so the Devanagari is written out and Tamil and IAST derived from');
out('-- it, as everywhere else. Idempotent.');
out('-- =============================================================================');
out('');
out('begin;');
out('');

for (const r of ROWS) {
  out(`update public.pooja_steps set
  mantra_sanskrit = ${q(r.deva)},
  mantra_tamil = ${q(transliterate(r.deva, TAMIL_SCHEME))},
  mantra_translit = ${q(transliterate(r.deva, 'iast'))},
  scripts_generated = true
where pooja_id = 'ganesha_standard' and step_title_en = ${q(r.step)};`);
  out('');
}

out('commit;');
out('');
out('-- Verify: expect 1, only Pushpa Pooja, whose content is the 20-name archana');
out('--   select step_title_en from pooja_steps where mantra_sanskrit is null;');

if (!emit) console.error('\n(no SQL written; pass --emit)');
