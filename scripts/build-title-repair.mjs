#!/usr/bin/env node
/**
 * Put the Tamil step titles back.
 *
 *   node scripts/build-title-repair.mjs --emit
 *
 * WHAT HAPPENED. 0025 built each new step like this:
 *
 *     const o = { ...s };                          // o.ta is the Tamil TITLE
 *     Object.assign(o, scripts(s.deva.join('\n'))) // scripts() also returns `ta`
 *
 * `scripts()` returns {deva, ta, iast} for the MANTRA. Assigning it over the
 * step object overwrote `ta` -- the Tamil title -- with the Tamil mantra, and
 * the insert then wrote that into step_title_ta. Twelve of the thirteen steps
 * were hit. The thirteenth, the archana list, has no mantra and so had nothing
 * to overwrite it.
 *
 * WHY NOTHING CAUGHT IT. checkScripts validates that a string is well-formed
 * Tamil, and a Tamil mantra is well-formed Tamil. The harness asserted that
 * step_title_ta is NOT NULL, and it was not null. proofread checks scripts and
 * truncation, not shape. Every gate was looking at the value and none was
 * looking at whether it was the right KIND of value.
 *
 * It surfaced in the UI review: the step-jump dropdown read
 * "Step 10: ஶுக்லாம்பரதரம் விஷ்ணும் ஶஶிவர்ணம்..." because the dropdown prints
 * the Tamil title.
 *
 * 0025 is fixed at source, so a fresh database is correct. This repairs the one
 * that already ran it.
 */
import { emitMigration } from './_migration.mjs';

/** The titles as 0025 always meant to write them. */
const TITLES = {
  'Vighneshwara Sankalpam': 'விக்னேஸ்வர சங்கல்பம்',
  'Sakala Devata Vandanam': 'ஸகல தேவதா வந்தனம்',
  'Deepa Pooja': 'தீப பூஜை',
  'Asana Pooja': 'ஆஸன பூஜை',
  'Vighneshwara Pooja': 'விக்னேஸ்வர பூஜை',
  'Vighneshwara Shodasha Nama Archana': 'விக்னேஸ்வர ஷோடஶ நாம அர்ச்சனை',
  'Vighneshwara Naivedyam & Neerajanam': 'விக்னேஸ்வர நைவேத்யம் & நீராஜனம்',
  'Vighneshwara Udvasanam': 'விக்னேஸ்வர உத்வாசனம்',
  'Shankha Pooja': 'ஶங்க பூஜை',
  'Atma Pooja': 'ஆத்ம பூஜை',
  'Peetha Pooja': 'பீட பூஜை',
  'Guru Dhyanam': 'குரு த்யானம்',
  'Upayana Danam': 'உபாயன தானம்',
};

let failed = false;
console.log('--- checking the replacements are titles, not mantras ---\n');
for (const [en, ta] of Object.entries(TITLES)) {
  if (ta.length > 60 || /[।॥\n]/.test(ta)) {
    failed = true;
    console.error(`  FAIL ${en}: the replacement is itself mantra-shaped`);
  }
  console.log(`  ${en.padEnd(38)} ${ta}`);
}
if (failed) process.exit(1);

const q = (s) => `'${String(s).replace(/'/g, "''")}'`;
const lines = [];
const out = (s = '') => lines.push(s);

out('-- =============================================================================');
out('-- 0029_repair_tamil_step_titles.sql');
out('--');
out('-- GENERATED by scripts/build-title-repair.mjs. Do not hand-edit.');
out('--');
out('-- 0025 wrote the Tamil MANTRA into step_title_ta on twelve of the thirteen');
out('-- steps it added. The generator did');
out('--     const o = { ...s }; Object.assign(o, scripts(s.deva.join(chr(10))));');
out('-- and scripts() returns a key called `ta` for the mantra, which landed on top');
out('-- of the step’s own `ta`, its title. The archana step has no mantra and so was');
out('-- the only one left intact.');
out('--');
out('-- Nothing caught it because every gate was checking the VALUE and none was');
out('-- checking what KIND of value it was: a Tamil mantra is well-formed Tamil, it');
out('-- is not null, and it is not truncated. It surfaced when the step-jump dropdown');
out('-- started reading "Step 10: shuklaambaradharam viSHNum...".');
out('--');
out('-- 0025 is fixed at source; this repairs a database that already ran it.');
out('--');
out('-- Idempotent, and guarded: it only touches a title that is still mantra-shaped,');
out('-- so a hand-corrected title is never overwritten.');
out('-- =============================================================================');
out();
out('begin;');
out();
for (const [en, ta] of Object.entries(TITLES)) {
  out(`update public.pooja_steps set step_title_ta = ${q(ta)}, updated_at = now()`);
  out(` where pooja_id = 'ganesha_standard' and step_title_en = ${q(en)}`);
  out(`   and (length(step_title_ta) > 60 or step_title_ta like '%' || chr(10) || '%'`);
  out(`        or step_title_ta like '%।%' or step_title_ta is null);`);
}
out();
out('-- --- assert -------------------------------------------------------------------');
out('do $$');
out('declare n int;');
out('begin');
out('  -- No title anywhere, in either language, may be mantra-shaped. This is the');
out('  -- check that did not exist when 0025 ran.');
out('  select count(*) into n from public.pooja_steps');
out('   where length(coalesce(step_title_en, \'\')) > 60');
out('      or length(coalesce(step_title_ta, \'\')) > 60');
out("      or step_title_en like '%' || chr(10) || '%'");
out("      or step_title_ta like '%' || chr(10) || '%'");
out("      or step_title_en like '%।%' or step_title_ta like '%।%'");
out("      or step_title_en like '%॥%' or step_title_ta like '%॥%';");
out("  if n > 0 then raise exception '% step titles still look like mantra text', n; end if;");
out('  -- and every step still has one.');
out('  select count(*) into n from public.pooja_steps');
out('   where step_title_en is null or step_title_ta is null;');
out("  if n > 0 then raise exception '% steps are missing a title', n; end if;");
out('end $$;');
out();
out('commit;');

const sql = lines.join('\n') + '\n';
if (process.argv.includes('--emit')) {
  emitMigration('supabase/migrations/0029_repair_tamil_step_titles.sql', sql);
} else {
  console.log('\n--- validated, not written (pass --emit) ---');
}
