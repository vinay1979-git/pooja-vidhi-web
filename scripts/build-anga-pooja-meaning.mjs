#!/usr/bin/env node
/**
 * The Anga Pooja's meaning still described the list 0032 replaced.
 *
 *   node scripts/build-anga-pooja-meaning.mjs          # validate
 *   node scripts/build-anga-pooja-meaning.mjs --emit   # write it
 *
 * WHAT HAPPENED. 0032 swapped Varalakshmi's fifteen-limb anga pooja for the
 * book's twenty-four and updated instruction_en to say so. It did not touch
 * meaning_en, which went on reading:
 *
 *   "Fourteen names, each naming a limb ... and a fifteenth for the whole body:
 *    Chanchala at the feet, Padmalaya at the navel, Kambukanthi at the throat..."
 *
 * Every one of those names had just been deleted from the step. The screen was
 * showing twenty-four offerings under a paragraph describing fifteen different
 * ones.
 *
 * WHY NOTHING CAUGHT IT. meaning_en was not null, not truncated, and well-formed
 * English. This is the same shape of failure as the titles 0025 clobbered: every
 * gate was checking whether the VALUE was well formed, and none was checking
 * whether it still described the data next to it. It surfaced only by opening
 * the step in the browser and reading the page.
 *
 * So this migration also comes with a proofread check: where a step has archana
 * rows and its meaning spells out a count, the count has to match the rows.
 */
import { emitMigration } from './_migration.mjs';

const MEANING =
  'Twenty-four names, each naming a limb, from the feet upward to the head, and a ' +
  'twenty-fourth for the whole body: Varalakshmi at the feet, Ksheerabdhitanaya at ' +
  'the thighs, Narayanapriya at the navel, Kambukanthi at the neck, Shiva at the ' +
  'head, and Sarvamangala for all the limbs together.';

/** The names this meaning cites, and where the book puts them (pp.121-123). */
// The assertion below matches on DEVANAGARI, not on the transliteration. A first
// version looked for '%varalaks%' in invoked_name_translit and failed, because
// the IAST is varalakSmyai with a retroflex S that carries a combining dot --
// 'varalaks' is not a prefix of it. The Devanagari has no such trap.
const CITED = [
  ['Varalakshmi', 1, 'feet', 'वरलक्ष्म्यै'],
  ['Ksheerabdhitanaya', 5, 'thighs', 'क्षीराब्धि'],
  ['Narayanapriya', 8, 'navel', 'नारायण'],
  ['Kambukanthi', 12, 'neck', 'कम्बुकण्ठ्यै'],
  ['Shiva', 23, 'head', 'शिवायै'],
  ['Sarvamangala', 24, 'whole body', 'सर्वमङ्गलायै'],
];

let failed = false;
console.log('--- the new meaning describes the list that is actually there ---');
if (!/Twenty-four names/.test(MEANING)) { failed = true; console.error('  FAIL: does not say twenty-four'); }
if (/fourteen|fifteen|Chanchala|Chapala|Padmalaya/i.test(MEANING)) {
  failed = true; console.error('  FAIL: still carries a word from the replaced list');
}
for (const [name, seq, limb] of CITED) {
  if (!MEANING.includes(name)) { failed = true; console.error(`  FAIL: does not cite ${name}`); }
  else console.log(`  cites ${name.padEnd(20)} (book seq ${String(seq).padStart(2)}, ${limb})`);
}
if (failed) { console.error('\nnot emitting'); process.exit(1); }

const q = (s) => `'${String(s).replace(/'/g, "''")}'`;
const lines = [];
const out = (s = '') => lines.push(s);

out('-- =============================================================================');
out('-- 0034_anga_pooja_meaning.sql');
out('--');
out('-- GENERATED by scripts/build-anga-pooja-meaning.mjs. Do not hand-edit.');
out('--');
out('-- 0032 replaced the fifteen-limb anga pooja with the book-s twenty-four and');
out('-- updated the instruction, but left meaning_en describing the list it had just');
out('-- deleted -- naming Chanchala, Padmalaya and Kambukanthi at limbs those names');
out('-- no longer occupy. The screen showed twenty-four offerings under a paragraph');
out('-- about fifteen different ones.');
out('--');
out('-- Nothing caught it because meaning_en was not null, not truncated and well-');
out('-- formed English. Same shape as the titles 0025 clobbered: the gates checked');
out('-- the value, not whether it still described the data beside it.');
out('--');
out('-- Idempotent: only rewrites a meaning that still mentions the old list.');
out('-- =============================================================================');
out();
out('begin;');
out();
out('update public.pooja_steps set');
out(`       meaning_en = ${q(MEANING)},`);
out('       updated_at = now()');
out(" where pooja_id = 'varalakshmi_vratham' and step_title_en = 'Anga Pooja'");
out("   and (meaning_en ilike '%fifteenth%' or meaning_en ilike '%Chanchala%');");
out();
out('-- --- assert ------------------------------------------------------------------');
out('do $$');
out('declare n int; m text; rows int;');
out('begin');
out("  select meaning_en into m from public.pooja_steps");
out("   where pooja_id = 'varalakshmi_vratham' and step_title_en = 'Anga Pooja';");
out("  if m ilike '%fifteenth%' or m ilike '%Chanchala%' or m ilike '%Padmalaya%' then");
out("    raise exception 'the anga pooja meaning still describes the replaced list'; end if;");
out("  if m not ilike '%twenty-four%' then");
out("    raise exception 'the anga pooja meaning does not say twenty-four'; end if;");
out();
out('  -- and it agrees with the rows actually stored');
out('  select count(*) into rows from public.archana_items a');
out('    join public.pooja_steps s on s.id = a.pooja_step_id');
out("   where s.pooja_id = 'varalakshmi_vratham' and s.step_title_en = 'Anga Pooja';");
out('  if rows <> 24 then');
out("    raise exception 'the anga pooja has % rows but its meaning says twenty-four', rows; end if;");
out();
out('  -- every name the meaning cites is actually in the list');
for (const [name, , , needle] of CITED) {
  out(`  select count(*) into n from public.archana_items a`);
  out('    join public.pooja_steps s on s.id = a.pooja_step_id');
  out("   where s.pooja_id = 'varalakshmi_vratham' and s.step_title_en = 'Anga Pooja'");
  out(`     and a.invoked_name_deva like ${q('%' + needle + '%')};`);
  out(`  if n < 1 then raise exception ${q('the meaning cites ' + name + ', which is not in the list')}; end if;`);
}
out('end $$;');
out();
out('commit;');

const sql = lines.join('\n') + '\n';
if (process.argv.includes('--emit')) {
  emitMigration('supabase/migrations/0034_anga_pooja_meaning.sql', sql);
  console.log('\nwrote supabase/migrations/0034_anga_pooja_meaning.sql');
} else {
  console.log('\n--- validated, not written (pass --emit) ---');
}
