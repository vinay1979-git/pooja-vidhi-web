#!/usr/bin/env node
/**
 * Let a pooja recommend a karta, and have Varalakshmi recommend a woman.
 *
 *   node scripts/build-karta-recommendation.mjs          # validate
 *   node scripts/build-karta-recommendation.mjs --emit   # write it
 *
 * WHY A NEW COLUMN WHEN `eligibility` ALREADY EXISTS.
 *
 * 0002 gave poojas an eligibility column constrained to all / male_only /
 * female_only / initiated_male_only. Nothing has ever set it to anything but
 * 'all', and nothing reads it. It would have been one UPDATE to put
 * 'female_only' on Varalakshmi and be done.
 *
 * That word is the problem. female_only is a PROHIBITION, and the book does not
 * make one. Its Varalakshmi chapter frames the vratham as kept "more so by the
 * women who are looked upon as the embodiment of Lakshmi", tells the whole
 * origin story through women -- Surachandrika, Shyama Bala, Charumati -- and
 * glosses Lakshmi's own disguise as "Suvasini (married woman)". Read the five
 * pages start to finish and the expectation is unmistakable. Read them again
 * looking for the sentence that says a man may not keep it, and it is not
 * there. Neither is it in the Purvanga section, which DOES gate something --
 * gaNaanaam tvaa, "can be recited only by those who have learnt it in the
 * proper intonation" -- and then supplies a substitute for those it excludes.
 * That is what this book looks like when it means to exclude someone.
 *
 * So the two things are modelled separately and honestly:
 *
 *   eligibility        who MAY. Still 'all' on all three poojas, because that
 *                      is what the source supports.
 *   karta_recommended  who the tradition EXPECTS. Varalakshmi: female.
 *
 * All the recommendation does in the app is pre-select a button. The other two
 * stay live, and picking one is not an error.
 *
 * Ganesha and the Nitya Panchayatana are left null on purpose. The daily rite
 * is commonly the male householder's in practice, but the book says nothing of
 * the kind and an app does not get to promote household custom to printed
 * instruction. Null means "this rite makes no recommendation", and the app then
 * makes none either.
 */
import { emitMigration } from './_migration.mjs';

const VALUES = ['male', 'female', 'couple'];

/** pooja id -> recommended karta, or null for no recommendation. */
const RECOMMEND = {
  varalakshmi_vratham: 'female',
  ganesha_standard: null,
  nitya_panchayatana: null,
};

let failed = false;
const fail = (m) => { failed = true; console.error('  FAIL ' + m); };

console.log('--- karta recommendation per pooja ---');
for (const [id, who] of Object.entries(RECOMMEND)) {
  console.log(`  ${id.padEnd(22)} ${who ?? '(none)'}`);
  if (who !== null && !VALUES.includes(who)) fail(`${id}: ${who} is not one of ${VALUES.join('/')}`);
}
const recommending = Object.values(RECOMMEND).filter(Boolean);
if (recommending.length !== 1) {
  fail(`expected exactly one pooja to recommend a karta, found ${recommending.length}`);
}
if (RECOMMEND.varalakshmi_vratham !== 'female') fail('Varalakshmi must recommend female');
if (failed) { console.error('\nnot emitting'); process.exit(1); }

const q = (s) => `'${String(s).replace(/'/g, "''")}'`;
const lines = [];
const out = (s = '') => lines.push(s);

out('-- =============================================================================');
out('-- 0041_karta_recommendation.sql');
out('--');
out('-- GENERATED by scripts/build-karta-recommendation.mjs. Do not hand-edit.');
out('--');
out('-- A pooja may now recommend a karta. Varalakshmi recommends a woman.');
out('--');
out('-- WHY NOT THE eligibility COLUMN THAT ALREADY EXISTS. It is constrained to');
out('-- all / male_only / female_only / initiated_male_only, and female_only is a');
out('-- PROHIBITION the book does not make. Its Varalakshmi chapter expects women --');
out('-- kept "more so by the women who are looked upon as the embodiment of Lakshmi",');
out('-- the origin story told entirely through Surachandrika, Shyama Bala and');
out('-- Charumati, Lakshmi herself disguised as a "Suvasini (married woman)" -- but');
out('-- it never writes that a man may not keep the vratham. When this book means to');
out('-- exclude someone it says so and offers a substitute; that is how it handles');
out('-- gaNaanaam tvaa in the Purvanga section.');
out('--');
out('--   eligibility        who MAY.      Left at all on every pooja.');
out('--   karta_recommended  who is EXPECTED. Varalakshmi: female.');
out('--');
out('-- Ganesha and the Nitya Panchayatana stay null. The daily rite is commonly the');
out('-- male householder\'s in practice, but the book says nothing of the kind, and');
out('-- household custom does not get promoted to printed instruction here.');
out('--');
out('-- In the app the recommendation only pre-selects a button. The other two stay');
out('-- live and choosing one is not an error state.');
out('-- =============================================================================');
out();
out('begin;');
out();
out('alter table public.poojas');
out('  add column if not exists karta_recommended text;');
out();
out('do $$ begin');
out('  alter table public.poojas');
out('    add constraint poojas_karta_recommended_ck');
out(`    check (karta_recommended in (${VALUES.map(q).join(', ')}));`);
out('exception when duplicate_object or duplicate_table then null; end $$;');
out();
out('comment on column public.poojas.karta_recommended is');
out(`  ${q('Who the tradition EXPECTS to perform this rite, or null for no recommendation. A recommendation, not a rule: see eligibility for who MAY. The app uses it only to pre-select the karta toggle.')};`);
out();
for (const [id, who] of Object.entries(RECOMMEND)) {
  out('update public.poojas set');
  out(`       karta_recommended = ${who === null ? 'null' : q(who)},`);
  out('       updated_at = now()');
  out(` where id = ${q(id)};`);
  out();
}
out('-- --- assert ------------------------------------------------------------------');
out('do $$');
out('declare n int; v text;');
out('begin');
out('  if to_regclass(\'public.poojas\') is null then');
out("    raise exception 'public.poojas is missing';");
out('  end if;');
out();
out('  -- The column exists and is nullable. A not-null default would have forced');
out('  -- every future pooja to claim a recommendation it may not have.');
out('  select count(*) into n from information_schema.columns');
out("   where table_schema = 'public' and table_name = 'poojas'");
out("     and column_name = 'karta_recommended' and is_nullable = 'YES';");
out("  if n <> 1 then raise exception 'karta_recommended is missing or not nullable'; end if;");
out();
for (const [id, who] of Object.entries(RECOMMEND)) {
  out(`  select karta_recommended into v from public.poojas where id = ${q(id)};`);
  out(`  if not found then raise notice ${q(id + ' is not in this database, skipping')};`);
  if (who === null) {
    out('  elsif v is not null then');
    out(`    raise exception ${q(id + ' recommends %, but it should recommend nobody')}, v;`);
  } else {
    out(`  elsif v is distinct from ${q(who)} then`);
    out(`    raise exception ${q(id + ' recommends %, expected ' + who)}, coalesce(v, 'nobody');`);
  }
  out('  end if;');
  out();
}
out('  -- The constraint rejects anything else. Checked by TRYING it, because a');
out('  -- constraint that exists and does not bite is the failure mode here, and');
out('  -- reading it out of pg_constraint would only prove it was written down.');
out('  -- The write is real and is rolled back by the subtransaction the exception');
out('  -- block opens, so nothing survives it.');
out('  select count(*) into n from public.poojas;');
out('  if n > 0 then');
out('    begin');
out("      update public.poojas set karta_recommended = 'priest'");
out('       where id = (select id from public.poojas order by id limit 1);');
out("      raise exception 'the check constraint let an invalid karta through';");
out('    exception when check_violation then null;');
out('    end;');
out('  end if;');
out();
out('  -- eligibility is deliberately untouched: this migration adds an expectation,');
out('  -- not a permission rule.');
out("  select count(*) into n from public.poojas where eligibility <> 'all';");
out("  if n > 0 then raise exception '% pooja(s) carry a non-all eligibility; this migration should not have set one', n; end if;");
out('end $$;');
out();
out('commit;');

const sql = lines.join('\n') + '\n';
if (process.argv.includes('--emit')) {
  emitMigration('supabase/migrations/0041_karta_recommendation.sql', sql);
  console.log('\nwrote supabase/migrations/0041_karta_recommendation.sql');
} else {
  console.log('\n--- validated, not written (pass --emit) ---');
}
