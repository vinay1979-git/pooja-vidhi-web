#!/usr/bin/env node
/**
 * Two words of the Vayana Dhanam mantra, corrected against the page.
 *
 *   node scripts/build-vayana-dhanam-repair.mjs          # validate
 *   node scripts/build-vayana-dhanam-repair.mjs --emit   # write 0058
 *
 * Varalakshmi's upayana formula (book p.137) was transcribed with two slips
 * that 0032 carried into the app:
 *
 *   सादुगुण्यं         for  साद्गुण्यं         (sādguṇyaṃ, "full efficacy"): the
 *                                               conjunct द्गु read as दु + गु
 *   सौमाङ्गल्यावािं    for  सौमाङ्गल्यावाप्तिं  (saumāṅgalyāvāptiṃ, "the gaining of
 *                                               married happiness"): the प्त lost
 *
 * The photograph prints both correctly, and so does the roman on the same
 * page (saadguNyam, saumaangalyaavaaptim). The transcript is corrected too, with
 * a finding block saying so.
 *
 * The Tamil and IAST columns are derived from the Devanagari, so each pair is
 * converted with the same transliterator that produced them and replaced in
 * place. The rest of the mantra is untouched.
 */
import Sanscript from '@indic-transliteration/sanscript';
import { transliterate } from './_tamil.mjs';
import { emitMigration } from './_migration.mjs';

const MIGRATION = 'supabase/migrations/0058_vayana_dhanam_typos.sql';
const STEP = `pooja_id = 'varalakshmi_vratham' and step_title_en = 'Vayana Dhanam'`;

const FIXES = [
  ['सादुगुण्यं', 'साद्गुण्यं'],
  ['सौमाङ्गल्यावािं', 'सौमाङ्गल्यावाप्तिं'],
];
const COLS = [['mantra_sanskrit', null], ['mantra_tamil', 'tamil'], ['mantra_translit', 'iast']];

const q = (s) => `'${s.replace(/'/g, "''")}'`;
const form = (w, to) => (to ? transliterate(Sanscript, w, to) : w);

let failed = false;
for (const [bad, good] of FIXES) {
  for (const [col, to] of COLS) {
    const b = form(bad, to), g = form(good, to);
    if (b === g) { failed = true; console.error(`FAIL ${col}: ${bad} and ${good} convert to the same text`); }
    console.log(`  ${col.padEnd(16)} ${b}  ->  ${g}`);
  }
}
if (failed) process.exit(1);
if (!process.argv.includes('--emit')) { console.log('\n(no SQL written; pass --emit)'); process.exit(0); }

const sets = COLS.map(([col, to]) =>
  FIXES.reduce((expr, [bad, good]) => `replace(${expr}, ${q(form(bad, to))}, ${q(form(good, to))})`, col),
);

const sql = `-- Two words of the Varalakshmi Vayana Dhanam mantra, corrected against book
-- p.137. Generated by scripts/build-vayana-dhanam-repair.mjs; see its header.

begin;

update public.pooja_steps set
  ${COLS.map(([col], i) => `${col} = ${sets[i]}`).join(',\n  ')},
  updated_at = now()
 where ${STEP}
   and (${COLS.flatMap(([col, to]) => FIXES.map(([bad]) => `position(${q(form(bad, to))} in ${col}) > 0`)).join('\n        or ')});

-- Afterwards no column may still carry a slip, and every column must carry the
-- correction. Re-runnable: on a second run the update matches nothing and these
-- still hold.
do $$
declare n int;
begin
  select count(*) into n from public.pooja_steps
   where ${STEP}
     and ${COLS.flatMap(([col, to]) => FIXES.map(([, good]) => `position(${q(form(good, to))} in ${col}) > 0`)).join('\n     and ')};
  if n <> 1 then raise exception 'Vayana Dhanam: a correction is missing from one of the three scripts'; end if;
  select count(*) into n from public.pooja_steps
   where ${STEP}
     and (${COLS.flatMap(([col, to]) => FIXES.map(([bad]) => `position(${q(form(bad, to))} in ${col}) > 0`)).join('\n          or ')});
  if n <> 0 then raise exception 'Vayana Dhanam: a slip survived'; end if;
end $$;

commit;
`;
emitMigration(MIGRATION, sql);
